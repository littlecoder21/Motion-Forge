export const readmeExport = (p: Project) => `# ${p.name}

Generated by MotionForge. Every file here runs the same motion engine as the live preview.

- \`Carousel.tsx\` + \`carousel-runtime.ts\` + \`carousel.css\` — React usage: \`import Carousel from './Carousel'\` and render \`<Carousel />\`.
- \`carousel.html\` — a complete standalone page.
- \`carousel.js\` — drop-in embed: add \`<div data-motionforge></div>\` and include the script.
- \`carousel-project.json\` — the editable project; import it back into MotionForge.
- \`assets/\` — uploaded images (if any).

No carousel library or framework is required. The engine respects \`prefers-reduced-motion\`, supports keyboard navigation, and pauses when off-screen.
`;

export function exportCode(kind: ExportKind, p: Project, o?: ExportOptions): string {
  switch (kind) {
    case 'React': return reactExport(p, o);
    case 'Runtime': return runtimeFile();
    case 'JS': return jsExport(p, o);
    case 'HTML': return htmlExport(p, o);
    case 'CSS': return cssExport(p, o);
    default: return projectJson(p);
  }
}
