import { createCarousel } from './runtime';
import { RUNTIME_CSS } from './runtime-css';
import type { Project } from './model';

export type ExportKind = 'React' | 'Runtime' | 'JS' | 'HTML' | 'CSS' | 'JSON';
export type ExportOptions = { ratio?: string };
export const EXPORT_FILES: Record<ExportKind, { file: string; mime: string; label: string }> = {
  React: { file: 'Carousel.tsx', mime: 'text/plain', label: 'React component' },
  Runtime: { file: 'carousel-runtime.ts', mime: 'text/plain', label: 'Motion engine' },
  JS: { file: 'carousel.js', mime: 'text/javascript', label: 'Vanilla JS embed' },
  HTML: { file: 'carousel.html', mime: 'text/html', label: 'Standalone page' },
  CSS: { file: 'carousel.css', mime: 'text/css', label: 'Stylesheet' },
  JSON: { file: 'carousel-project.json', mime: 'application/json', label: 'Editable project' },
};

const ratioOf = (o?: ExportOptions) => (o?.ratio && o.ratio !== 'auto' ? o.ratio : '16 / 9');
/** Runtime config = the project itself. Escaped so it is safe inside <script> blocks. */
const configJson = (p: Project, pretty = false) => JSON.stringify(p, null, pretty ? 2 : 0).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
/** The exact function the live preview runs, serialised. Self-contained by design. */
const engine = () => createCarousel.toString();

export const projectJson = (p: Project) => JSON.stringify(p, null, 2);

export const cssExport = (_p: Project, o?: ExportOptions) =>
  `/* MotionForge carousel — drop this next to your markup */\n${RUNTIME_CSS}\n#carousel{--mf-ratio:${ratioOf(o)}}\n`;

export const runtimeFile = () =>
  `// @ts-nocheck\n/* eslint-disable */\n// MotionForge motion engine — framework-free, no dependencies. Generated; edit the project in MotionForge instead.\nexport type CarouselApi = { update(config: any): void; goTo(index: number, silent?: boolean): void; go(direction: number): void; setPlaying(value: boolean): void; getIndex(): number; destroy(): void };\nexport const createCarousel: (root: HTMLElement, config: any, hooks?: any) => CarouselApi = ${engine()};\nexport default createCarousel;\n`;

export const reactExport = (p: Project, o?: ExportOptions) => `import { useEffect, useRef } from 'react';
import type { CSSProperties } from 'react';
import { createCarousel } from './carousel-runtime';
import './carousel.css';

// Generated by MotionForge — "${p.name.replace(/\*\//g, '')}"
const config = ${configJson(p, true)};

export function Carousel({ className }: { className?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!ref.current) return;
    const carousel = createCarousel(ref.current, config);
    return () => carousel.destroy();
  }, []);
  return <div ref={ref} className={className} style={{ '--mf-ratio': '${ratioOf(o)}' } as CSSProperties} />;
}

export default Carousel;
`;

export const jsExport = (p: Project, o?: ExportOptions) => `/* MotionForge carousel — add <div data-motionforge></div> anywhere, then include this file with <script src="carousel.js" defer></script>. */
(function () {
  var createCarousel = ${engine()};
  var css = ${JSON.stringify(RUNTIME_CSS)};
  var config = ${configJson(p)};
  function mount(el) {
    if (el.__mf) return el.__mf;
    if (!el.style.getPropertyValue('--mf-ratio')) el.style.setProperty('--mf-ratio', ${JSON.stringify(ratioOf(o))});
    el.__mf = createCarousel(el, config);
    return el.__mf;
  }
  function boot() {
    if (!document.getElementById('mf-runtime-css')) {
      var s = document.createElement('style'); s.id = 'mf-runtime-css'; s.textContent = css; document.head.appendChild(s);
    }
    var nodes = document.querySelectorAll('[data-motionforge]');
    for (var i = 0; i < nodes.length; i++) mount(nodes[i]);
  }
  window.MotionForge = { mount: mount, config: config, createCarousel: createCarousel };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot); else boot();
})();
`;

